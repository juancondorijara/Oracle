--CREAR TABLA
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(250) NOT NULL,
    ROLE VARCHAR2(50) NOT NULL,
    STATE CHAR(1) NOT NULL
);

CREATE TABLE CUSTOMER (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DNI VARCHAR2(8) NOT NULL,
    CELLPHONE VARCHAR2(9) NOT NULL,
    FIRST_NAME VARCHAR2(50) NOT NULL,
    LAST_NAME VARCHAR2(50) NOT NULL,
    STATE CHAR(1) NOT NULL,
    CONSTRAINT UK_CUSTOMER_DNI UNIQUE (DNI),
    CONSTRAINT UK_CUSTOMER_CELLPHONE UNIQUE (CELLPHONE)
);


CREATE TABLE PRODUCT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(150) NOT NULL,
    PURCHASE_PRICE DECIMAL(5,2) NOT NULL,
    SALE_PRICE DECIMAL(5,2) NOT NULL,
    STOCK NUMBER NOT NULL,
    STATE CHAR(1) NOT NULL
);


CREATE TABLE SALE (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    SALE_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TOTAL NUMBER(5,2) NOT NULL,
    STATE CHAR(1) NOT NULL,
    CONSTRAINT FK_SALE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(ID)
);


CREATE TABLE SALE_DETAIL (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SALE_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    QUANTITY NUMBER NOT NULL,
    SUBTOTAL NUMBER(5,2) NOT NULL,
    STATE CHAR(1) NOT NULL,
    CONSTRAINT FK_SALE_DETAIL_SALE FOREIGN KEY (SALE_ID) REFERENCES SALE(ID),
    CONSTRAINT FK_SALE_DETAIL_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(ID)
);


